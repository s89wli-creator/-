export const messages: Record<Locale, Record<MessageKey, string>> = { ar, en };

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let s = messages[locale][key] ?? messages.ar[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function errorMessage(locale: Locale, code: string | undefined): string {
  const key = `errors.${code}` as MessageKey;
  return key in messages.ar ? translate(locale, key) : translate(locale, 'errors.UNKNOWN');
}

